from pattern import Pattern
from copy import deepcopy


P1 = Pattern([[1, 2], [1], [1]], [[1/8, 1/8], [1/4], [1/4]], [], [])
P2 = Pattern([[1], [0], [0], [1], [2], [2], [1]],
             [[1/4], [1/2], [1/4], [3/4], [1/4], [1/2], [1/2]], [], [])
P3 = Pattern(
    [[0, 0, 0, 0], [1], [0, 1, 2], [0], [0]],
    [[1/8, 1/8, 1/8, 1/8], [3/8], [1/8, 3/8, 1/8], [1/2], [1/2]],
    [],
    []
)


def get_pattern(n):
    return deepcopy([P1, P2, P3][n - 1])
    